#!/usr/bin/env python3
"""Build a README.md index for each prompt folder.

Each index lists the prompts in the folder with the sections they cover,
taken from the bold section headings in the prompt. Run from the repo root:

    python3 scripts/build_index.py            # rebuild all folder indexes
    python3 scripts/build_index.py aws azure  # rebuild selected folders
"""

import pathlib
import re
import sys

ROOT = pathlib.Path.cwd()

FOLDERS = {
    "ai": "AI and LLM Security Prompts",
    "ansible": "Ansible Security Prompts",
    "aws": "AWS Security Prompts",
    "azure": "Azure Security Prompts",
    "cicd": "CI/CD Security Prompts",
    "code-quality": "Code Quality Prompts",
    "docker": "Docker and Container Security Prompts",
    "gcp": "Google Cloud Security Prompts",
    "iac": "Other IaC Tool Security Prompts",
    "identity": "Identity Security Prompts",
    "kubernetes": "Kubernetes Security Prompts",
    "monitoring": "Logging, Monitoring and Detection Prompts",
    "network": "Network Security Prompts",
    "python": "Python Security and Style Prompts",
    "saas": "SaaS Security Prompts",
    "security": "Cross-Cloud Security Prompts",
    "terraform": "Terraform Security Prompts",
}

MAX_SECTIONS = 8

HEADING = re.compile(r"^\*\*(.+?):\*\*\s*$")
NUMBERED = re.compile(r"^\*\*\d+\.\s*(.+?):\*\*\s*$")


def describe(path: pathlib.Path) -> tuple[str, str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    title = lines[0].lstrip("# ").strip()
    title = re.sub(r"\s+Prompt$", "", title)
    sections = []
    for line in lines:
        m = NUMBERED.match(line) or HEADING.match(line)
        if m:
            sections.append(m.group(1))
    if len(sections) > MAX_SECTIONS:
        sections = sections[:MAX_SECTIONS] + ["and more"]
    return title, ", ".join(sections)


def build(folder: str) -> None:
    base = ROOT / folder
    if not base.is_dir():
        return
    prompts = sorted(
        p for p in base.rglob("*.md") if p.name != "README.md"
    )
    rows = []
    for p in prompts:
        title, covers = describe(p)
        rel = p.relative_to(base).as_posix()
        rows.append(f"| [{title}]({rel}) | {covers} |")
    body = [
        f"# {FOLDERS.get(folder, folder.title())}",
        "",
        "Copy a prompt into your AI assistant, add your requirements, and review the output before use.",
        "",
        "| Prompt | Covers |",
        "|---|---|",
        *rows,
        "",
        "This file is generated by `scripts/build_index.py`. Do not edit it by hand.",
        "",
    ]
    (base / "README.md").write_text("\n".join(body), encoding="utf-8")
    print(f"{folder}: {len(rows)} prompts")


def main() -> None:
    folders = sys.argv[1:] or list(FOLDERS)
    for folder in folders:
        build(folder)


if __name__ == "__main__":
    main()
